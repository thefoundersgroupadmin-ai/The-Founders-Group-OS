#!/usr/bin/env python3
"""Generate the TFG brand files from config/tfg/brand.yaml (or a client's file).

    python3 scripts/tfg-brand.py                       # TFG itself
    python3 scripts/tfg-brand.py --brand config/tfg/clients/acme.yaml
    python3 scripts/tfg-brand.py --check               # fail if generated files are stale

Writes:
  desktop/backend-go/internal/founderos/brand/brand_gen.go
  frontend/src/lib/founderos/brand.gen.ts
  config/founderos/engine-topology.yaml   (workspace name/holds only)
"""
import argparse
import json
import pathlib
import re
import shutil
import subprocess
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
GO_OUT = ROOT / "desktop/backend-go/internal/founderos/brand/brand_gen.go"
TS_OUT = ROOT / "frontend/src/lib/founderos/brand.gen.ts"
TOPOLOGY = ROOT / "config/founderos/engine-topology.yaml"

SLOTS = ["vantage", "launchpad-cohort"]          # stable internal keys
WORKSPACES = ["founderos", "vantage", "launchpad-cohort", "personal"]
AREAS = ["marketing", "sales", "communication", "finances", "clients", "knowledge", "operations"]
HEX = re.compile(r"^#[0-9a-fA-F]{6}$")


def load(path: pathlib.Path) -> dict:
    b = yaml.safe_load(path.read_text())
    errs = []
    for k in ["company", "short", "operator", "product_name", "product_tagline", "workspaces", "ventures", "impact"]:
        if k not in b:
            errs.append(f"missing top-level key: {k}")
    for ws in WORKSPACES:
        w = b.get("workspaces", {}).get(ws) or {}
        if not w.get("name") or not w.get("holds"):
            errs.append(f"workspaces.{ws} needs name and holds")
    for slot in SLOTS:
        v = b.get("ventures", {}).get(slot) or {}
        for k in ["label", "kind", "color", "detail", "focus", "area_agents"]:
            if k not in v:
                errs.append(f"ventures.{slot}.{k} is missing")
        if v.get("color") and not HEX.match(v["color"]):
            errs.append(f"ventures.{slot}.color must be #rrggbb")
        for area in (v.get("area_agents") or {}):
            if area not in AREAS:
                errs.append(f"ventures.{slot}.area_agents.{area}: area must be one of {AREAS}")
    lm = b.get("ventures", {}).get("vantage", {}).get("lead_match")
    if not lm:
        errs.append("ventures.vantage.lead_match is missing")
    else:
        try:
            re.compile(lm.replace("(?i)", ""))
        except re.error as e:
            errs.append(f"ventures.vantage.lead_match is not a valid regex: {e}")
    for h in b.get("hide_views") or []:
        if not str(h).startswith("/os/") or h == "/os":
            errs.append(f"hide_views: {h!r} must be an /os/<view> path (Home cannot be hidden)")
    hc = b.get("hide_connectors") or []
    if not isinstance(hc, list) or not all(isinstance(x, str) and re.fullmatch(r"[a-z0-9-]+", x) for x in hc):
        errs.append("hide_connectors must be a list of connector ids, e.g. [robinhood]")
    if not isinstance(b.get("cohort_invite", False), bool):
        errs.append("cohort_invite must be true or false")
    mpr = (b.get("impact") or {}).get("minutes_per_successful_run")
    if not isinstance(mpr, int) or mpr <= 0:
        errs.append("impact.minutes_per_successful_run must be a positive whole number")
    if errs:
        sys.exit("brand file is invalid:\n  - " + "\n  - ".join(errs))
    return b


def gq(s: str) -> str:
    """A Go string literal."""
    return json.dumps(s, ensure_ascii=False)


def go_source(b: dict, src: str) -> str:
    out = [
        f"// Code generated by scripts/tfg-brand.py from {src}. DO NOT EDIT.",
        "",
        "package brand",
        "",
        f"const Company = {gq(b['company'])}",
        f"const Short = {gq(b['short'])}",
        f"const Operator = {gq(b['operator'])}",
        f"const LeadMatch = {gq(b['ventures']['vantage']['lead_match'])}",
        f"const MinutesPerSuccessfulRun = {int(b['impact']['minutes_per_successful_run'])}",
        "",
        "// HiddenConnectors are left off the Connections board (hide_connectors).",
        f"var HiddenConnectors = []string{{{', '.join(gq(x) for x in (b.get('hide_connectors') or []))}}}",
        "",
        "var WorkspaceNames = map[string]string{",
    ]
    for ws in WORKSPACES:
        out.append(f"\t{gq(ws)}: {gq(b['workspaces'][ws]['name'])},")
    out += ["}", "", "var Ventures = []Venture{"]
    for slot in SLOTS:
        v = b["ventures"][slot]
        out.append("\t{")
        out.append(f"\t\tID: {gq(slot)}, Label: {gq(v['label'])}, Kind: {gq(v['kind'])}, Color: {gq(v['color'])},")
        out.append(f"\t\tDetail: {gq(v['detail'])},")
        out.append("\t\tFocus: []string{")
        for f in v["focus"]:
            out.append(f"\t\t\t{gq(f)},")
        out.append("\t\t},")
        out.append("\t\tAreaAgents: map[string][]string{")
        for area in AREAS:
            ids = v["area_agents"].get(area, [])
            out.append(f"\t\t\t{gq(area)}: {{{', '.join(gq(i) for i in ids)}}},")
        out.append("\t\t},")
        out.append("\t},")
    out += ["}", ""]
    return "\n".join(out)


def gofmt(src: str) -> str:
    """gofmt the generated Go when gofmt is installed (keeps --check stable)."""
    if not shutil.which("gofmt"):
        return src
    return subprocess.run(["gofmt"], input=src, capture_output=True, text=True, check=True).stdout


def ts_source(b: dict, src: str) -> str:
    v = b["ventures"]
    labels = {s: v[s]["label"] for s in SLOTS}
    colors = {s: v[s]["color"] for s in SLOTS}
    names = {ws: b["workspaces"][ws]["name"] for ws in WORKSPACES}
    return "\n".join([
        f"// Code generated by scripts/tfg-brand.py from {src}. DO NOT EDIT.",
        "",
        f"export const COMPANY = {json.dumps(b['company'])};",
        f"export const COMPANY_SHORT = {json.dumps(b['short'])};",
        f"export const OPERATOR = {json.dumps(b['operator'])};",
        f"export const PRODUCT_NAME = {json.dumps(b['product_name'])};",
        f"export const PRODUCT_TAGLINE = {json.dumps(b['product_tagline'])};",
        f"export const HIDDEN_VIEWS: readonly string[] = {json.dumps(list(b.get('hide_views') or []))};",
        f"export const SHOW_COHORT_INVITE = {'true' if b.get('cohort_invite', False) else 'false'};",
        f"export const VENTURE_LABEL = {json.dumps(labels, ensure_ascii=False)} as const;",
        f"export const VENTURE_COLOR = {json.dumps(colors)} as const;",
        f"export const WORKSPACE_NAMES = {json.dumps(names, ensure_ascii=False)} as const;",
        "",
    ])


def topology_source(b: dict) -> str:
    text = TOPOLOGY.read_text()
    for ws in WORKSPACES:
        w = b["workspaces"][ws]
        pat = re.compile(r"^(\s*- \{slug: " + re.escape(ws) + r", )name: [^,]+(, home: [^,]+, class: [^,]+, )holds: \"[^\"]*\"\}", re.M)
        repl = r"\g<1>name: " + w["name"].replace("\\", "") + r"\g<2>holds: " + json.dumps(w["holds"]) + "}"
        text, n = pat.subn(lambda m: m.expand(repl), text)
        if n != 1:
            sys.exit(f"engine-topology.yaml: could not find workspace {ws!r}")
    return text


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--brand", default="config/tfg/brand.yaml")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--validate", action="store_true", help="only check the brand file itself")
    a = ap.parse_args()
    path = (ROOT / a.brand).resolve()
    b = load(path)
    if a.validate:
        print(f"brand file is valid: {b['company']}")
        return
    src = str(path.relative_to(ROOT))
    outputs = {GO_OUT: gofmt(go_source(b, src)), TS_OUT: ts_source(b, src), TOPOLOGY: topology_source(b)}
    stale = [p for p, body in outputs.items() if not p.exists() or p.read_text() != body]
    if a.check:
        if stale:
            sys.exit("stale brand files (run scripts/tfg-brand.py): " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
        print("brand files are current")
        return
    for p, body in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(body)

    print(f"brand: {b['company']} -> {len(outputs)} files ({len(stale)} changed)")


if __name__ == "__main__":
    main()
